// Content checker + manifest generator (node, no dependencies).
//   node tools/check.js          check everything; fails if abc/manifest.js is out of date
//   node tools/check.js --fix    regenerate abc/manifest.js (script order, offline file list, version hash)
// Exit code 1 on errors; warnings don't fail. CI runs it on every push / PR.
const fs = require('fs'), path = require('path'), vm = require('vm'), crypto = require('crypto');
const root = path.join(__dirname, '..'), rel = p => path.relative(root, p).split(path.sep).join('/');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const exists = p => fs.existsSync(path.join(root, p));
const ls = (dir, re) => exists(dir) ? fs.readdirSync(path.join(root, dir)).filter(f => re.test(f)).sort().map(f => `${dir}/${f}`) : [];
const FIX = process.argv.includes('--fix');
let errors = 0, warnings = 0;
const err = m => { console.log('  ERROR ' + m); errors++; };
const warn = m => { console.log('  warn  ' + m); warnings++; };

// ---------- 1. config → script order ----------
const ctx = vm.createContext({ console, Intl, self: {} });
const run = f => vm.runInContext(read(f) + '\n;globalThis.ABC = ABC;', ctx, { filename: f });
run('abc/core/registry.js'); run('abc/core/i18n.js'); run('abc/config.js');
const CFG = ctx.ABC.config;
const scripts = ['abc/core/registry.js', 'abc/core/i18n.js', 'abc/config.js', 'abc/concepts.js'];
for (const c of CFG.languages) {
  for (const f of ['grammar', 'strings', 'words', 'info']) { const p = `abc/lang/${c}/${f}.js`; if (exists(p)) scripts.push(p); else if (f !== 'info') err(`language ${c}: missing ${p}`); }
}
scripts.push('abc/core/content.js');
for (const m of CFG.modules) {
  if (!exists(`abc/modules/${m}/module.js`)) { err(`module ${m}: missing abc/modules/${m}/module.js`); continue; }
  scripts.push(...ls(`abc/modules/${m}`, /^(?!module\.js).*\.js$/), `abc/modules/${m}/module.js`);
  for (const c of CFG.languages) { const p = `abc/modules/${m}/lang/${c}.js`; if (exists(p)) scripts.push(p); }
}
scripts.push('abc/core/services.js', ...ls('abc/core/views', /\.js$/), ...ls('abc/core/games', /\.js$/), 'abc/core/shell.js');
// files cached for offline use (every language, every module)
const files = ['abc.html', 'abc/manifest.js', ...scripts, 'manifest-abc.json', 'abc-icon-192.png', 'abc-icon-512.png',
  ...ls('fonts', /\.woff2$/), 'rocket.html', 'paint.html', 'manifest.json', 'manifest-paint.json',
  'icon-192.png', 'icon-512.png', 'paint-icon-192.png', 'paint-icon-512.png'].filter(exists);
const hash = crypto.createHash('sha256'); files.filter(f => f !== 'abc/manifest.js').forEach(f => hash.update(f).update(fs.readFileSync(path.join(root, f))));
const version = hash.digest('hex').slice(0, 10);
const manifest = `// GENERATED by \`node tools/check.js --fix\` — do not edit by hand.\n// scripts: load order of abc.html · files: cached for offline use by sw.js · version: content hash\n` +
  `self.MANIFEST = ${JSON.stringify({ version, scripts, files }, null, 2)};\n`;
if (FIX) { fs.writeFileSync(path.join(root, 'abc/manifest.js'), manifest); console.log(`manifest written: ${scripts.length} scripts, ${files.length} files, version ${version}`); }
else if (!exists('abc/manifest.js') || read('abc/manifest.js') !== manifest) err('abc/manifest.js is out of date — run `node tools/check.js --fix`');

// ---------- 2. load content (no DOM files) ----------
for (const f of scripts.slice(3)) { if (/^abc\/core\/(services|shell|views\/)/.test(f)) continue; run(f); }
const ABC = ctx.ABC, langs = CFG.languages, base = CFG.baseLanguage;
ABC.errors.forEach(err);
const keysOf = (o, p = '') => Object.entries(o || {}).flatMap(([k, v]) => v && typeof v === 'object' && !Array.isArray(v) && !('other' in v) ? keysOf(v, p + k + '.') : [p + k]);

console.log(`languages: ${langs.join(', ')} (base ${base})`);
for (const c of langs) {
  const L = ABC.langs[c]; if (!L) { err(`${c}: not loaded`); continue; }
  for (const k of ['name', 'flag', 'bcp47', 'letters', 'numbers', 'sayLetter', 'forms']) if (L[k] == null) err(`${c}: grammar.js missing "${k}"`);
  if (L.numbers && L.numbers.length !== 10) err(`${c}: numbers must have 10 entries`);
  try { new Intl.Locale(L.bcp47); } catch (e) { err(`${c}: bcp47 "${L.bcp47}" is not a valid locale`); }
  const bk = keysOf(ABC.langs[base].strings), ck = new Set(keysOf(L.strings));
  for (const k of bk) if (!ck.has(k)) err(`${c}/strings.js: missing "${k}" (would show ${base} text)`);
  for (const s of CFG.sections) if (!(L.strings.sections || {})[s.id]) err(`${c}/strings.js: sections.${s.id} missing`);
}

console.log(`concepts: ${ABC.concepts.length}`);
const used = new Set();
for (const c of ABC.concepts) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(c.id)) err(`concept "${c.id}": id must be an ASCII slug`);
  if (!/\p{Extended_Pictographic}|\p{Regional_Indicator}|⃣/u.test(c.pic)) warn(`concept "${c.id}": picture "${c.pic}" is not an emoji`);
}
for (const c of langs) {
  const L = ABC.langs[c]; if (!L) continue;
  const seenW = new Map();
  for (const e of L.words) {
    used.add(e.id);
    if (!ABC.conceptById[e.id]) { err(`${c}/words.js: unknown concept "${e.id}" (add it to abc/concepts.js)`); continue; }
    const w = (e.w || '').split('/').join('');
    if (!w.trim()) err(`${c}/words.js ${e.id}: empty word`);
    for (const [k, v] of Object.entries(e)) if (typeof v === 'string') {
      if (v !== v.normalize('NFC')) err(`${c}/words.js ${e.id}.${k}: not NFC-normalized`);
      if (c === 'ro' && /[şţŞŢ]/.test(v)) err(`ro/words.js ${e.id}.${k}: cedilla ş/ţ — use comma-below ș/ț`);
    }
    try { L.forms(e, w); } catch (x) { err(`${c}/words.js ${e.id}: forms → ${x.message}`); }
    if (L.checkForms) { const m = L.checkForms(e); if (m) warn(`${c}/words.js ${e.id}: ${m}`); }
    const key = w.toLocaleLowerCase(L.bcp47);
    if (seenW.has(key)) err(`${c}/words.js: "${w}" is used for two concepts (${seenW.get(key)}, ${e.id}) — add a note or pick another word`);
    seenW.set(key, e.id);
  }
  for (const id of Object.keys(L.info || {})) {
    const I = L.info[id];
    if (!ABC.conceptById[id]) err(`${c}/info.js: card "${id}" has no concept`);
    if (!I.title || !Array.isArray(I.lines) || !I.lines.length) err(`${c}/info.js ${id}: needs title + lines`);
    const b = ABC.langs[base].info[id]; if (b && b.lines.length !== I.lines.length) warn(`${c}/info.js ${id}: ${I.lines.length} lines, ${base} has ${b.lines.length}`);
  }
  const missing = ABC.concepts.filter(x => !L.words.some(e => e.id === x.id)).length;
  if (missing) warn(`${c}: ${missing}/${ABC.concepts.length} concepts have no word in this language`);
}
for (const x of ABC.concepts) if (!used.has(x.id) && !ABC.modules.some(m => JSON.stringify(m).includes(`'${x.id}'`))) warn(`concept "${x.id}" is used by no language`);

console.log(`modules: ${CFG.modules.join(', ')}`);
const tileIds = new Map();
for (const id of CFG.modules) {
  const m = ABC.modules.find(m => m.id === id); if (!m) { err(`module ${id}: MODULE('${id}') not found`); continue; }
  for (const t of m.tiles || []) {
    if (tileIds.has(t.id)) err(`tile "${t.id}" defined in modules ${tileIds.get(t.id)} and ${id}`); tileIds.set(t.id, id);
    if (!CFG.sections.some(s => s.id === (t.section || m.section))) err(`tile ${t.id}: unknown section`);
    if (t.view && !exists(`abc/core/views/${t.view}.js`)) err(`tile ${t.id}: unknown view "${t.view}"`);
    if (t.game && !exists(`abc/core/games/${t.game.type}.js`)) err(`tile ${t.id}: unknown game type "${t.game.type}"`);
  }
  for (const c of langs) {
    const s = m.strings[c];
    if (!s) { warn(`module ${id}: no strings for ${c} → hidden in ${c}`); continue; }
    const S = m.build ? m.build(c) : {};
    for (const t of m.tiles || []) {
      const lab = s.tiles && s.tiles[t.id];
      const items = t.items ? t.items(S) || [] : [];
      if (t.view && !items.length) { if (lab) warn(`${c}: tile ${t.id} has a label but no items → hidden`); continue; }
      if (!Array.isArray(lab) || lab.length !== 2) { if (t.view || items.length) err(`module ${id}/${c}: tiles.${t.id} must be [learn label, game label]`); else warn(`module ${id}/${c}: tiles.${t.id} missing → hidden`); continue; }
      if (!t.game) continue;
      const pool = ((t.game.items || t.items)(S) || []).filter(it => !it.noPlay);
      if (pool.length < 2) err(`${c}: game ${t.id} has ${pool.length} playable items (needs ≥ 2)`);
      const asks = new Set(pool.flatMap(it => [false, true].map(lower => t.game.ask ? t.game.ask(it, { lower }) : t.id)));
      for (const k of asks) if (!(s.games || {})[k]) err(`module ${id}/${c}: games.${k} (spoken question) missing`);
    }
    if (S.letters) { const bare = S.letters.filter(l => !l.examples.length).map(l => l.id); if (bare.length) err(`${c}: letters with no example word: ${bare.join(' ')}`); }
    if (id === 'colors' && s.colors && s.colors.rainbow && !(S.colors || []).some(x => x.id === 'rainbow')) err(`${c}: rainbow needs all 7 band names (closed set)`);
  }
}
console.log(errors ? `\n${errors} error(s), ${warnings} warning(s)` : `\nOK — ${warnings} warning(s)`);
process.exit(errors ? 1 : 0);
